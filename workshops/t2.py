class ClassificationHead:
    """ส่วนหัวสำหรับการจำแนกคดี IP"""
    def __init__(self, hidden_size=768, n_classes=3, dropout=0.1):
        self.W = np.random.randn(n_classes, hidden_size) * 0.01
        self.b = np.zeros(n_classes)
        self.dropout = dropout

    def forward(self, h_cls, training=False):
        # Dropout ทำงานเฉพาะช่วง Training[cite: 3]
        if training:
            mask = (np.random.rand(*h_cls.shape) > self.dropout)
            h_cls = h_cls * mask / (1 - self.dropout)
        
        logits = h_cls @ self.W.T + self.b
        # Softmax เพื่อหาความมั่นใจ (Confidence)
        e = np.exp(logits - logits.max(axis=-1, keepdims=True))
        return e / e.sum(axis=-1, keepdims=True)

class BERTForClassification:
    CLASS_NAMES = ["ละเมิด_สิทธิบัตร", "ละเมิด_ลิขสิทธิ์", "ไม่ละเมิด"]

    def __init__(self, seed=42):
        self.rng = np.random.RandomState(seed)
        self.head = ClassificationHead()
        self.tokenizer = MockTokenize()

    def predict_proba(self, texts):
        batch_size = len(texts)
        # จำลอง h_cls จาก BERT Encoder (768 dim)[cite: 3]
        h_cls = self.rng.randn(batch_size, 768)
        return self.head.forward(h_cls)

    def show_results(self, texts):
        probs = self.predict_proba(texts)
        preds = np.argmax(probs, axis=1)
        print(f"\n{'ข้อความ':<40} | {'การทำนาย':<18} | {'ความมั่นใจ'}")
        print("-" * 75)
        for text, p, pr in zip(texts, preds, probs):
            print(f"{text[:38]:<40} | {self.CLASS_NAMES[p]:<18} | {pr[p]*100:.2f}%")

