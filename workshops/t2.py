class MockTokenize:
    """จำลองการทำงานของ BERT Tokenizer เพื่อวิเคราะห์โครงสร้าง input_ids"""
    def encode(self, texts, max_length=32):
        if isinstance(texts, str): texts = [texts]
        input_ids, attention_mask = [], []
        for text in texts:
            # โครงสร้าง: [CLS]=1, token_ids..., [SEP]=2, [PAD]=0
            ids = [1] + [ord(c) % 5000 + 100 for c in text[:(max_length - 2)]] + [2]
            pad_len = max_length - len(ids)
            mask = [1] * len(ids) + [0] * pad_len
            ids = ids + [0] * pad_len
            input_ids.append(ids[:max_length])
            attention_mask.append(mask[:max_length])
        return {"input_ids": np.array(input_ids), "attention_mask": np.array(attention_mask)}

    def show(self, text, max_length=32):
        enc = self.encode([text], max_length)
        ids = enc["input_ids"][0]
        print(f"\n  ข้อความ: '{text}'")
        print(f"  โครงสร้าง ID: [CLS]={ids[0]}, tokens={ids[1:5].tolist()}..., [SEP]={ids[np.where(ids==2)[0][0]]}, [PAD]={ids[-1]}")

