def vocab_expansion_analysis():
    print("\n" + "="*50 + "\n4.2 Vocabulary Expansion & Warm-up\n" + "="*50)
    # จำลอง embedding ก่อนและหลัง Warm-up
    np.random.seed(42)
    old_emb = np.array([0.82, -0.34, 0.56, 0.91])
    new_before = np.random.randn(4) * 0.02 # Random ❗
    new_after = old_emb * 0.6 + np.random.randn(4) * 0.1 # มีทิศทางแล้ว
    
    def cosine(a, b): return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))
    
    print(f"  Cosine Similarity (ก่อน Warm-up): {cosine(old_emb, new_before):.3f}")
    print(f"  Cosine Similarity (หลัง Warm-up): {cosine(old_emb, new_after):.3f}")
    print("  *หมายเหตุ: Warm-up ช่วยป้องกัน Catastrophic Forgetting*")

