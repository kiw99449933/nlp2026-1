import numpy as np
from imblearn.over_sampling import SMOTE
from collections import Counter
import torch

def balance_legal_data(X, y):
    counts = Counter(y)
    min_samples = min(counts.values())
    
    # โจทย์ o: หาก min_samples = 1 SMOTE จะทำงานไม่ได้ (ไม่มีคู่สำหรับสร้างจุดใหม่)[cite: 2]
    if min_samples > 1:
        # ปรับ k_neighbors ให้ไม่เกินจำนวนตัวอย่างที่มี[cite: 2]
        k = min(5, min_samples - 1)
        sampler = SMOTE(k_neighbors=k, random_state=42)
        X_res, y_res = sampler.fit_resample(X, y)
    else:
        from imblearn.over_sampling import RandomOverSampler
        sampler = RandomOverSampler(random_state=42)
        X_res, y_res = sampler.fit_resample(X, y)
    
    return X_res, y_res

# การเตรียมข้อมูลสำหรับ LSTM (โจทย์ q)[cite: 2]
# X_res_3d shape: (Batch, Seq_Len, Input_Size)
# ในที่นี้กำหนด Seq_Len=1 เพื่อให้สอดคล้องกับ TF-IDF 1 vector ต่อ 1 doc[cite: 2]

import torch.nn as nn

class LegalBiLSTM(nn.Module):
    def __init__(self, input_dim=50, hidden_dim=32, output_dim=3): # input_dim ตาม max_features[cite: 2]
        super(LegalBiLSTM, self).__init__()
        self.lstm = nn.LSTM(input_dim, hidden_dim, batch_first=True, bidirectional=True)
        # โจทย์ s: BiLSTM มี 2 ทิศทาง ต้องใช้ hidden_dim * 2[cite: 2]
        self.fc = nn.Linear(hidden_dim * 2, output_dim)
        nn.init.xavier_uniform_(self.fc.weight) # โจทย์ u: ช่วยคุม variance ของ gradient[cite: 2]

    def forward(self, x):
        lstm_out, _ = self.lstm(x)
        # Mean Pooling เพื่อรวมข้อมูลจากทุก time step[cite: 2]
        pooled = torch.mean(lstm_out, dim=1)
        return self.fc(pooled)

class LegalLSTM(nn.Module):
    def __init__(self, input_dim=50, hidden_dim=32, output_dim=3):
        super(LegalLSTM, self).__init__()
        self.lstm = nn.LSTM(input_dim, hidden_dim, batch_first=True, bidirectional=False)
        self.fc = nn.Linear(hidden_dim, output_dim)
        nn.init.xavier_uniform_(self.fc.weight)

    def forward(self, x):
        lstm_out, _ = self.lstm(x)
        pooled = torch.mean(lstm_out, dim=1)
        return self.fc(pooled)

