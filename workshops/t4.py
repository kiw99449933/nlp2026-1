import random

LEGAL_SYNONYMS = {
    "ละเมิด": ["ฝ่าฝืน", "กระทำผิด", "ล่วงสิทธิ"],
    "จำหน่าย": ["ขาย", "เผยแพร่", "กระจายสินค้า"],
    "ปลอมแปลง": ["ทำเทียม", "เลียนแบบ"],
    # เพิ่ม Synonym ใหม่ (โจทย์ m)
    "ทำซ้ำ": ["คัดลอก", "ผลิตซ้ำ"], 
    "ดัดแปลง": ["แก้ไข", "ปรับปรุงจากต้นฉบับ"]
}

def augment_legal_text(text):
    # ในสภาวะจริงควรใช้ ThaiLegalTokenizer.tokenize(text)
    # สมมติว่า text ถูกแยกคำด้วย space มาแล้วสำหรับตัวอย่างนี้
    words = text.split()
    new_words = words.copy()
    for i, word in enumerate(words):
        if word in LEGAL_SYNONYMS:
            new_words[i] = random.choice(LEGAL_SYNONYMS[word])
    return " ".join(new_words)

